import test from 'node:test';
import assert from 'node:assert/strict';
import { execFileSync } from 'node:child_process';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { launchServer } from '../scripts/lib/server.mjs';

test('AI 的 Git 查询固定版本、按关系独立着色；分页与聚焦保留画布及待应用比较', async t => {
  const root = fs.mkdtempSync(path.join(os.tmpdir(), 'cg-read-changes-'));
  t.after(() => fs.rmSync(root, { recursive: true, force: true, maxRetries: 3 }));
  const git = (...args) => execFileSync('git', ['-C', root, ...args], { windowsHide: true });
  git('init', '--quiet');
  git('config', 'core.autocrlf', 'false');
  const before = 'void stable(void) {}\nvoid gone(void) {}\nvoid work(void) { stable(); gone(); }\nTASK(A) { work(); }\nISR(B) { work(); }';
  const after = before.replace('void gone', 'void fresh').replace('stable(); gone();', 'stable(); fresh();');
  const file = path.join(root, 'app.c');
  fs.writeFileSync(file, before);
  git('add', 'app.c');
  git('-c', 'user.name=Test', '-c', 'user.email=test@example.invalid', 'commit', '--quiet', '-m', 'baseline');
  fs.writeFileSync(file, after);
  const srv = await launchServer({ target: root });
  t.after(srv.close);
  const get = async url => (await fetch(srv.baseUrl + url)).json();
  const post = async (url, body) => {
    const res = await fetch(srv.baseUrl + url, { method: 'POST', headers: { 'Content-Type': 'application/json' },
      body: JSON.stringify(body) });
    const result = await res.json();
    assert.equal(result.ok, true, result.error);
    return result;
  };
  const read = args => get('/api/mcp-changes?' + new URLSearchParams(args));
  const id = name => 'app.c::' + name;
  const pageBefore = await get('/api/page');
  const opts = { mode: 'git', baseRef: 'HEAD', targetRef: 'WORKTREE' };
  const prepared = await post('/api/compare', opts);
  const initial = await read({ limit: 1 });
  assert.equal(initial.ok, true, initial.error);
  assert.equal(initial.source, 'git');
  assert.equal(initial.total, 5);
  const snapshotId = initial.snapshotId;
  const next = await read({ snapshotId, offset: initial.nextOffset });
  assert.equal(initial.nodes.length + next.nodes.length, 3);
  assert.deepEqual(next.edges.map(e => e.detectedChange).sort(), ['added', 'deleted']);
  fs.writeFileSync(file, before);
  const focus = await read({ snapshotId, id: id('work'), traceLimit: 1 });
  assert.equal(focus.nodes.find(n => n.id === id('work')).detectedChange, 'modified');
  assert.equal(focus.nodes.find(n => n.id === id('stable')).change, 'existing');
  assert.deepEqual(focus.edges.filter(e => e.from === id('work')).map(e => [e.to, e.change]).sort(),
    [[id('stable'), 'existing'], [id('fresh'), 'added'], [id('gone'), 'deleted']].sort());
  assert.ok(focus.edges.every(e => e.comparisonKey && e.edgeKey && (e.locations.before || e.locations.after)));
  assert.equal(focus.trace.totalTasks, 2);
  assert.equal(focus.trace.nextOffset, 1);
  const second = await read({ snapshotId, id: id('work'), traceOffset: focus.trace.nextOffset });
  assert.notEqual(second.trace.upstreamTasks[0].id, focus.trace.upstreamTasks[0].id);
  const removed = await read({ snapshotId, id: id('gone') });
  assert.equal(removed.trace.traceVersion, 'before');
  assert.deepEqual(removed.trace.upstreamChains[0].path.slice(-2), [id('work'), id('gone')]);
  const clean = await read({});
  assert.equal(clean.total, 0);
  assert.equal(clean.git.noSourceChanges, true);
  fs.writeFileSync(file, after);
  const unchanged = await read({ id: id('gone'), snapshotId: clean.snapshotId });
  assert.equal(unchanged.trace.traceVersion, 'after');
  assert.ok(unchanged.edges.every(e => e.detectedChange === 'existing'));
  assert.equal((await read({ snapshotId })).ok, false);
  assert.deepEqual(await get('/api/page'), pageBefore);
  // 临时读取没有改动 UI 之前生成的比较，应用的是原来那份快照。
  const applied = await post('/api/compare/apply', { previewId: prepared.preview.id, selectedIds: [id('work')] });
  await post('/api/compare/status', { comparisonId: applied.comparison.id, nodeId: id('work'), change: 'existing' });
  const active = await read({ id: id('work') });
  assert.equal(active.source, 'active-comparison');
  assert.equal(active.snapshotId, applied.comparison.id);
  const work = active.nodes.find(n => n.id === id('work'));
  assert.deepEqual([work.detectedChange, work.change, work.statusSource], ['modified', 'existing', 'manual']);
  assert.equal((await read({ snapshotId: clean.snapshotId })).ok, false);
  assert.equal((await read({ targetRef: 'INDEX' })).ok, false);
  await post('/api/compare/exit', {});
  assert.equal((await read({ snapshotId: clean.snapshotId })).ok, false);
  const forbidden = await fetch(srv.baseUrl + '/api/mcp-changes', { headers: { Origin: 'https://example.invalid' } });
  assert.equal(forbidden.status, 403);
  const stale = await fetch(srv.baseUrl + '/api/mcp-changes', { headers: { 'X-Callgraph-Session': '-1' } });
  assert.equal(stale.status, 409);
});

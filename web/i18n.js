const STORAGE_KEY = 'callgraph.language';
const translatorFor = createMessageCatalog(messages);

let lang = SUPPORTED_LANGS[0];
try {
  const saved = globalThis.localStorage?.getItem(STORAGE_KEY);
  if (SUPPORTED_LANGS.includes(saved)) lang = saved;
} catch { /* 离线或禁用存储时使用默认语言。 */ }
const snapshotLang = globalThis.__EXPORT?.snapshot?.language;
if (SUPPORTED_LANGS.includes(snapshotLang)) lang = snapshotLang;

let translate = translatorFor(lang);

export function getLang() {
  return lang;
}

export function setLang(value) {
  if (!SUPPORTED_LANGS.includes(value) || value === lang) return;
  lang = value;
  translate = translatorFor(lang);
  try { globalThis.localStorage?.setItem(STORAGE_KEY, lang); } catch { /* 当前页面仍可切换。 */ }
  if (typeof document === 'undefined') return;
  applyI18n();
  document.dispatchEvent(new CustomEvent('callgraph:langchange', { detail: { lang } }));
}

export function t(key, vars) {
  return translate(key, vars);
}

export function applyI18n(root = document) {
  for (const el of root.querySelectorAll('[data-i18n]')) el.textContent = t(el.dataset.i18n);
  // 富文本词条只支持行内代码和粗体，其他内容一律作为文本显示。
  for (const el of root.querySelectorAll('[data-i18n-rich]')) {
    const parts = t(el.dataset.i18nRich).split(/(`[^`]+`|\*\*[^*]+\*\*)/g);
    el.replaceChildren(...parts.map((part, index) => {
      if (index % 2 === 0) return part;
      const code = part.startsWith('`');
      const inline = document.createElement(code ? 'code' : 'strong');
      inline.textContent = code ? part.slice(1, -1) : part.slice(2, -2);
      return inline;
    }));
  }
  for (const [suffix, attr] of [['ph', 'placeholder'], ['title', 'title'], ['aria-label', 'aria-label'], ['alt', 'alt']]) {
    for (const el of root.querySelectorAll('[data-i18n-' + suffix + ']')) {
      el.setAttribute(attr, t(el.getAttribute('data-i18n-' + suffix)));
    }
  }
  if (root === document) document.documentElement.lang = lang;
}
